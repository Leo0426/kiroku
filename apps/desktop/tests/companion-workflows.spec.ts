import {test, expect} from '@playwright/test'
import {overrideApi, seedLibrary} from './helpers'
test.beforeEach(async({page})=>seedLibrary(page))

test('a selected missing companion is added and undone without replacing existing files', async({page})=>{
  await page.goto('/')
  await page.locator('input[placeholder*="搜索"]').first().fill('ABQ-100')
  await page.locator('button.pcard').filter({hasText:'ABQ-100'}).first().click()
  const panel=page.getByRole('complementary',{name:'影片详情'})
  const section=panel.getByRole('region',{name:'只补资料'})
  await section.getByRole('button',{name:'只补资料',exact:true}).click()
  await expect(section.getByRole('checkbox',{name:'NFO',exact:true})).toBeDisabled()
  await expect(section.getByRole('checkbox',{name:'海报',exact:true})).toBeChecked()
  const fanart=section.getByRole('checkbox',{name:'背景图'})
  if(await fanart.isEnabled())await fanart.uncheck()
  const apply=section.getByRole('button',{name:'确认补齐 1 个文件'})
  await expect(section).toContainText('poster.jpg')
  await apply.click()
  await expect(section.getByRole('status')).toContainText('已写入 1 个文件')
  await section.getByRole('button',{name:'撤销本次补资料'}).click()
  await section.getByRole('button',{name:'重新检查'}).click()
  await expect(section.getByRole('checkbox',{name:'海报',exact:true})).toBeChecked()
})

test('export a film, preview locked title replacement, restore, and undo from history', async({page})=>{
  await overrideApi(page,`window.testApi=api;
    const transfer=api.packageExport;
    api.packageExport=async(...args)=>{const result=await transfer(...args);window.mockPackagePath=result.destination;return result};
    api.pickDirectory=async title=>title.includes('保存')?'/mock/output':window.mockPackagePath;
  `)
  await page.goto('/')
  await page.locator('button.pcard').first().click()
  const panel=page.getByRole('complementary',{name:'影片详情'})
  const code=await panel.locator('.head .code').innerText(), original=await panel.locator('.head h2').innerText()
  const exportBox=panel.getByRole('region',{name:'导出资料包',exact:true})
  await exportBox.getByRole('button',{name:'导出资料包',exact:true}).click()
  await exportBox.getByRole('button',{name:'选择保存位置'}).click()
  await exportBox.getByRole('button',{name:'预览资料包'}).click()
  await exportBox.getByRole('button',{name:'确认导出副本'}).click()
  await expect(exportBox.getByRole('status')).toContainText('已导出 1 部影片')
  await page.evaluate(async code=>{const a=(window as any).testApi; const p=await a.revisionPreview(code,{title:'导出后修改'}); await a.revisionSave(p.token,p.root,p.code)},code)
  await panel.getByRole('button',{name:'关闭详情'}).click()
  await page.getByRole('button',{name:'媒体库工具',exact:true}).click()
  const restore=page.getByRole('region',{name:'资料包导回'})
  await restore.getByRole('button',{name:'从资料包导回'}).click()
  await restore.getByRole('button',{name:'选择资料包文件夹'}).click()
  await restore.getByRole('button',{name:'预览导回'}).click()
  await expect(restore.getByRole('button',{name:/确认导回/})).toBeDisabled()
  await restore.getByRole('button',{name:'修改导回规则'}).click()
  await restore.getByLabel('标题导回规则',{exact:true}).selectOption('replace')
  await restore.getByRole('button',{name:'预览导回'}).click()
  await restore.getByText('查看字段差异和写入文件').click()
  await expect(restore).toContainText('导出后修改')
  await expect(restore).toContainText(original)
  await restore.getByRole('button',{name:/确认导回/}).click()
  await expect(restore.getByRole('status')).toContainText('已导回 1 部影片')
  const currentTitle=()=>page.evaluate(async code=>(await (window as any).testApi.libraryGet(code)).meta.title,code)
  expect(await currentTitle()).toBe(original)
  await page.getByRole('navigation').getByRole('button',{name:'历史',exact:true}).click()
  await page.getByRole('button',{name:'撤销',exact:true}).first().click()
  await page.getByRole('button',{name:'确认撤销',exact:true}).click()
  await expect.poll(currentTitle).toBe('导出后修改')
})
