import { expect, test } from '@playwright/test'
import { overrideApi, seedLibrary } from './helpers'

test.beforeEach(async ({ page }) => seedLibrary(page))

test('drafts follow their film and library and restore only edited fields', async ({ page }) => {
  await overrideApi(page, `const get = api.libraryGet; api.libraryGet = async code => {
    const d = await get(code);
    if (d && window.updatedStudio) d.meta.studio = window.updatedStudio;
    return d;
  };`)
  await page.goto('/')
  const cards = page.locator('button.pcard')
  const panel = page.getByRole('complementary', { name: '影片详情' })
  const editor = panel.getByRole('region', { name: '人工编辑' })
  const edit = editor.getByRole('button', { name: '编辑元数据', exact: true })
  const title = editor.getByLabel('编辑标题', { exact: true })
  const close = panel.getByRole('button', { name: '关闭详情' })
  const setRoot = (root: string) => page.evaluate(async root => {
    const { app } = await import('/src/lib/state.svelte.ts')
    await app.setLibraryRoot(root)
  }, root)

  await cards.first().click()
  await edit.click()
  await title.fill('影片草稿')
  await editor.getByRole('button', { name: '添加演员' }).click()
  const lastActor = editor.getByLabel(/^演员姓名 /).last()
  await expect(lastActor).toBeFocused()
  await lastActor.fill('新增演员')
  await expect(editor.getByRole('status')).toHaveText('已改 2 项')
  await close.click()
  await cards.nth(1).click()
  await expect(edit).not.toContainText('草稿')
  await close.click()

  await setRoot('/mock/another-library')
  await cards.first().click()
  await expect(edit).not.toContainText('草稿')
  await close.click()
  await setRoot('/mock/library')
  await page.evaluate(() => { (window as any).updatedStudio = '另行更新的片商' })
  await cards.first().click()
  await expect(edit).toContainText('草稿')
  await edit.click()
  await expect(title).toHaveValue('影片草稿')
  await expect(lastActor).toHaveValue('新增演员')
  await expect(editor.getByLabel('编辑片商', { exact: true })).toHaveValue('另行更新的片商')
  await editor.getByRole('button', { name: '取消编辑' }).click()
  await expect(edit).toBeFocused()
  await expect(edit).not.toContainText('草稿')
  await edit.click()
  await expect(title).not.toHaveValue('影片草稿')
  await expect(editor.getByRole('button', { name: '预览差异' })).toBeDisabled()
})

test('keyboard previews the changed fields and saving retires the film draft', async ({ page }) => {
  await page.goto('/')
  await page.locator('button.pcard').first().click()
  const panel = page.getByRole('complementary', { name: '影片详情' })
  const editor = panel.getByRole('region', { name: '人工编辑' })
  const edit = editor.getByRole('button', { name: '编辑元数据', exact: true })
  await edit.click()
  await expect(editor.getByRole('button', { name: '预览差异' })).toBeDisabled()
  const plot = editor.getByLabel('编辑简介', { exact: true })
  await plot.fill('草稿简介')
  await panel.getByRole('button', { name: /^(收藏|取消收藏)$/ }).click()
  await expect(plot).toHaveValue('草稿简介')
  await plot.press('Control+Enter')
  const preview = editor.getByLabel('修订差异预览')
  await expect(preview.getByRole('heading', { name: '核对本次修改' })).toBeFocused()
  await expect(preview.locator('.change')).toHaveCount(1)
  await expect(preview.locator('ins')).toHaveText('草稿简介')
  await preview.getByRole('button', { name: '返回修改' }).click()
  await expect(plot).toBeFocused()
  await plot.press('Meta+Enter')
  await preview.getByRole('button', { name: '确认保存' }).click()
  await expect(panel.locator('.plot')).toHaveText('草稿简介')
  await expect(edit).not.toContainText('草稿')
  await edit.click()
  await expect(editor.getByRole('button', { name: '预览差异' })).toBeDisabled()
})

test('reading a long detail keeps navigation reachable, with arrows scoped to browsing', async ({ page }) => {
  await page.setViewportSize({ width: 800, height: 600 })
  await page.goto('/')
  await page.locator('button.pcard').first().click()
  const panel = page.getByRole('complementary', { name: '影片详情' })
  const next = panel.getByRole('button', { name: '下一部影片' })
  const firstCode = await panel.locator('.head .code').innerText()
  await panel.focus()
  await panel.evaluate(el => el.scrollTop = el.scrollHeight)
  await expect.poll(() => next.evaluate(el => el.getBoundingClientRect().top)).toBeGreaterThanOrEqual(0)
  await page.keyboard.press('ArrowRight')
  await expect(panel.locator('.head .code')).not.toHaveText(firstCode)
  await expect.poll(() => panel.evaluate(el => el.scrollTop)).toBe(0)
  await page.keyboard.press('ArrowLeft')
  await expect(panel.locator('.head .code')).toHaveText(firstCode)

  await panel.getByRole('button', { name: '编辑元数据', exact: true }).click()
  const title = panel.getByLabel('编辑标题', { exact: true })
  await title.fill('临时编辑')
  await title.press('ArrowRight')
  await expect(panel.locator('.head .code')).toHaveText(firstCode)
  await expect(title).toBeFocused()
})
