test('export cancellation is request owned and discards late results after library changes', async ({ page }) => {
  await overrideApi(page, `window.cancelled=[];api.libraryExportCsv=async(q,id)=>{window.exportStarted=id;return await new Promise(resolve=>window.finishExport=resolve)};api.jobCancel=async id=>{window.cancelled.push(id);return true}`)
  await page.goto('/'); await ready(page)
  await page.getByRole('button', { name: '导出 CSV', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).exportStarted)).toBeTruthy()
  await page.getByRole('button', { name: '停止导出', exact: true }).click()
  await page.evaluate(async () => { const { emitMock } = await import('/src/lib/events.ts'); emitMock('job:started', { jobId: 987, requestId: (window as any).exportStarted }) })
  await expect.poll(() => page.evaluate(() => (window as any).cancelled)).toEqual([987])
  await page.evaluate(async () => { const { app } = await import('/src/lib/state.svelte.ts'); app.settings = { ...app.settings!, library_root: '/mock/other' }; (window as any).finishExport(600) })
  await expect(page.getByText('已导出 600 部影片的 CSV 清单')).toHaveCount(0)
})

