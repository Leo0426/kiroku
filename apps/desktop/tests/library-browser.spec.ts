test('real mock export honors owned cancellation and produces no partial download', async ({ page }) => {
  await page.goto('/'); await ready(page)
  const downloads: string[] = []; page.on('download', d => downloads.push(d.suggestedFilename()))
  const result = await page.evaluate(async () => {
    const { api } = await import('/src/lib/api.ts')
    const { listen } = await import('/src/lib/events.ts')
    let owner: number | null = null
    const stopStarted = await listen('job:started', e => { if (e.requestId === 'export-cancel-test') owner = e.jobId })
    const stopProgress = await listen('library:export', e => { if (e.jobId === owner) void api.jobCancel(owner!) })
    try { await api.libraryExportCsv({}, 'export-cancel-test'); return 'unexpected success' }
    catch (e) { return String(e) }
    finally { stopStarted(); stopProgress() }
  })
  expect(result).toContain('导出已停止'); expect(downloads).toEqual([])
})

