import { expect, test } from '@playwright/test'
import { seedLibrary } from './helpers'

test('settings separates daily options and keeps syntax help collapsed', async ({ page }) => {
  await seedLibrary(page)
  await page.goto('/')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByLabel('目录模板')).toHaveCount(0)
  await page.getByRole('tab', { name: '命名与 NFO', exact: true }).click()
  await expect(page.getByLabel('目录模板')).toBeVisible()
  await expect(page.getByLabel('模板实时预览')).toBeVisible()
  await expect(page.getByText(/actors\/actresses 用/)).not.toBeVisible()
  await page.getByText('模板语法与占位符', { exact: true }).click()
  await expect(page.getByText(/actors\/actresses 用/)).toBeVisible()
  await page.getByLabel('目录模板').fill('{code}/{title}')
  await page.getByRole('tab', { name: '扫描', exact: true }).click()
  await page.getByLabel('最小体积').fill('50')
  await page.getByRole('button', { name: '恢复本页默认', exact: true }).click()
  await expect(page.getByLabel('最小体积')).toHaveValue('0')
  await page.getByRole('tab', { name: '命名与 NFO', exact: true }).click()
  await expect(page.getByLabel('目录模板')).toHaveValue('{code}/{title}')
  await page.getByRole('button', { name: /^保存更改/ }).click()
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('kiroku-mock-settings-v2')!).dir_template)).toBe('{code}/{title}')
})

test('settings categories work with keyboard and fit a small desktop window', async ({ page }) => {
  await page.setViewportSize({ width: 960, height: 720 })
  await seedLibrary(page)
  await page.goto('/')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '常规', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('tab', { name: '整理', exact: true })).toBeFocused()
  await expect(page.getByLabel('整理方式')).toBeVisible()
  await page.getByLabel('整理方式').selectOption('symlink')
  await expect(page.getByText(/软链接依赖源位置/)).toBeVisible()
  await expect(page.getByLabel('整理后清理原文件夹')).toBeDisabled()
  await page.getByRole('tab', { name: '命名与 NFO', exact: true }).click()
  await page.screenshot({ path: '/tmp/kiroku-settings-naming.png' })
  for (const width of [960, 720]) {
    await page.setViewportSize({ width, height: 720 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(page.getByRole('button', { name: /^保存更改/ })).toBeVisible()
    const input = await page.getByLabel('文件名模板').boundingBox()
    expect(input!.width).toBeGreaterThan(180)
  }
})

 test('source shortcut opens and locates the route editors', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('kiroku-mock-settings-v2', JSON.stringify({ library_root: '/mock/library', sources: [{ id: 'xcity', enabled: true, base: 'https://xcity.jp' }] })))
  await page.goto('/')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '数据源', exact: true }).click()
  await page.getByRole('button', { name: '编辑路线与字段优先级', exact: true }).click()
  await expect(page.getByRole('tab', { name: '高级', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#settings-routes')).toHaveAttribute('open', '')
  await expect(page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^字段优先级$/ }) })).toHaveAttribute('open', '')
  await expect(page.locator('#settings-routes')).toBeInViewport()
})
