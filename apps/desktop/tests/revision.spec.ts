test('closing detail discards a delayed preview', async ({ page }) => {
  await overrideApi(page, `const preview = api.revisionPreview; api.revisionPreview = async (...args) => { const p = await preview(...args); await new Promise(r => setTimeout(r, 700)); return p; };`)
  await page.goto('/'); await page.locator('button.pcard').first().click()
  await page.getByRole('button', { name: '编辑元数据' }).click()
  await page.getByLabel('编辑标题', { exact: true }).fill('stale')
  await page.getByRole('button', { name: '预览差异' }).click()
  await page.getByRole('button', { name: '关闭详情' }).click()
  await page.locator('button.pcard').nth(1).click()
  await page.waitForTimeout(900)
  await expect(page.getByLabel('修订差异预览')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '编辑元数据' })).toBeVisible()
})
test('all editable fields, empty locks and original source actions are represented honestly', async ({ page }) => {
  await overrideApi(page, `window.testApi = api; window.openedSources = []; api.openSourceUrl = async url => window.openedSources.push(url);`)
  await page.goto('/'); await page.locator('button.pcard').first().click()
  const panel = page.getByLabel('影片详情', { exact: true })
  const code = await panel.locator('.head .code').innerText()
  await panel.getByRole('button', { name: '编辑元数据' }).click()
  for (const [label, value] of Object.entries({ 标题: '', 简介: '新简介', 类别: '新类别', 片商: '新片商', 发行商: '新发行商', 系列: '新系列', 发行日期: '2026-01-02', 时长: '99', 导演: '新导演' })) {
    await panel.getByLabel(`编辑${label}`, { exact: true }).fill(value)
  }
  while (await panel.getByRole('button', { name: /^删除演员 / }).count()) await panel.getByRole('button', { name: /^删除演员 / }).last().click()
  await panel.getByRole('button', { name: '添加演员', exact: true }).click()
  await panel.getByLabel('演员姓名 1', { exact: true }).fill('新演员')
  await panel.getByRole('button', { name: '预览差异' }).click()
  await expect(panel.getByLabel('修订差异预览').locator('.change')).toHaveCount(10)
  await panel.getByRole('button', { name: '确认保存' }).click()
  await expect(panel.locator('h2')).toHaveText(code)
  const meta = await page.evaluate(async code => (await (window as any).testApi.libraryGet(code)).meta, code)
  expect(meta.locked_fields).toHaveLength(10)
  expect(meta.title).toBeNull()
  expect(meta.directors).toEqual(['新导演'])
  expect(meta.actors).toEqual([{ name: '新演员', gender: 'unknown' }])
  expect(await page.evaluate(() => (window as any).openedSources)).toEqual([])
  await panel.locator('summary').click()
  await panel.getByRole('button', { name: 'JavDB 原站' }).click()
  expect(await page.evaluate(() => (window as any).openedSources)).toEqual(['https://javdb.com/'])
})
test('library changes invalidate a candidate even after switching back', async ({ page }) => {
  await overrideApi(page, 'window.testApi = api;')
  await page.goto('/'); await page.locator('button.pcard').first().click()
  const code = await page.getByLabel('影片详情', { exact: true }).locator('.head .code').innerText()
  const message = await page.evaluate(async code => {
    const api = (window as any).testApi
    const preview = await api.revisionPreview(code, { title: 'stale' })
    await api.setLibraryRoot('/mock/other')
    await api.setLibraryRoot(preview.root)
    try { await api.revisionSave(preview.token, preview.root, code); return 'unexpected success' } catch (e) { return String(e) }
  }, code)
  expect(message).toContain('预览已过期')
})
test('actor rows and line lists accept plain names, preserve gender, and support removal and clearing', async ({ page }) => {
  await overrideApi(page, 'window.testApi = api;')
  await page.goto('/'); await page.locator('button.pcard').first().click()
  const panel = page.getByLabel('影片详情', { exact: true })
  const code = await panel.locator('.head .code').innerText()
  const before = await page.evaluate(async code => (await (window as any).testApi.libraryGet(code)).meta, code)
  await panel.getByRole('button', { name: '编辑元数据' }).click()
  await expect(panel).not.toContainText('JSON')
  await panel.getByRole('button', { name: '添加演员', exact: true }).click()
  const index = before.actors.length + 1
  await panel.getByLabel(`演员姓名 ${index}`, { exact: true }).fill('名叫"花"的演员')
  await panel.getByLabel(`演员性别 ${index}`, { exact: true }).selectOption('unknown')
  await panel.getByLabel('编辑类别', { exact: true }).fill('日常\n含"引号"的类别')
  await panel.getByLabel('编辑导演', { exact: true }).fill('新导演\n第二位导演')
  await panel.getByRole('button', { name: '预览差异' }).click()
  await expect(panel.getByLabel('修订差异预览')).toContainText('名叫"花"的演员（未知）')
  await expect(panel.getByLabel('修订差异预览')).not.toContainText('"gender"')
  await panel.getByRole('button', { name: '确认保存' }).click()
  await expect(panel.getByRole('button', { name: '编辑元数据' })).toBeVisible()
  const saved = await page.evaluate(async code => (await (window as any).testApi.libraryGet(code)).meta, code)
  expect(saved.actors.slice(0, -1)).toEqual(before.actors)
  expect(saved.locked_fields.sort()).toEqual(['actors', 'directors', 'tags'])
  await panel.getByRole('button', { name: '编辑元数据' }).click()
  while (await panel.getByRole('button', { name: /^删除演员 / }).count()) await panel.getByRole('button', { name: /^删除演员 / }).last().click()
  await panel.getByLabel('编辑类别', { exact: true }).fill('')
  await panel.getByLabel('编辑导演', { exact: true }).fill('')
  await panel.getByRole('button', { name: '预览差异' }).click()
  await panel.getByRole('button', { name: '确认保存' }).click()
  await expect(panel.getByRole('button', { name: '编辑元数据' })).toBeVisible()
  const cleared = await page.evaluate(async code => (await (window as any).testApi.libraryGet(code)).meta, code)
  expect(cleared.actors).toEqual([]); expect(cleared.tags).toEqual([]); expect(cleared.directors).toEqual([])
})
